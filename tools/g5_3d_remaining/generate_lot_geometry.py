"""Generate native Flutter geometry from the unified app manifest. --check for CI."""
import argparse
from pathlib import Path

from unified_geometry_contract import load_manifest, native_catalogue_specs


ROOT = Path(__file__).resolve().parents[2]
DATA = native_catalogue_specs(load_manifest())
NATIVE_CATALOGUE_ORDER = (
    'external-air-conditioner',
    'external-compressor',
    'external-freezer',
    'external-conveyor',
    'external-iron',
    'external-mixer',
    'external-computer',
    'external-pump-3p',
    'external-pump-ac1',
    'external-solar-pump',
    'external-refrigerator',
    'external-refrigerator-dc',
    'external-tv',
    'external-fan-ac1',
    'external-fan-3p',
    'pv-resistive-load',
    'source-ac3-grid',
    'source-ac3-alternator',
    'load-wye-3p',
    'load-delta-3p',
    'impedance',
    'energy-meter-ac1',
    'energy-meter-ac3',
    'energy-meter-pv',
    'power_socket_ac',
    'power_socket_dc',
)
HEADER = """// Generated by tools/g5_3d_remaining/generate_lot_geometry.py. Do not hand edit.
import 'dart:ui';
import 'package:electrosim_domain/electrosim_domain.dart';

class NativeApplianceGeometry {
  const NativeApplianceGeometry({
    required this.key,
    required this.visualType,
    required this.variant,
    required this.designSize,
    required this.boardSize,
    required this.ports,
    required this.serviceBox,
    required this.threePhase,
  });
  final String key, visualType, variant;
  final Size designSize, boardSize;
  final List<Offset> ports;
  final Rect serviceBox;
  final bool threePhase;
  List<Offset> offsets(Size size, int count) => [
    for (final p in ports.take(count))
      Offset(
        (p.dx / designSize.width - .5) * size.width,
        (p.dy / designSize.height - .5) * size.height,
      ),
  ];
  static NativeApplianceGeometry? forVisual(String type, String? variant) {
    final normalized = type == 'catalog_motor_driven_2t' && variant == 'pump'
        ? 'pump-ac1'
        : variant ??
              (type == 'power_socket_ac'
                  ? 'socket-ac'
                  : type == 'power_socket_dc'
                  ? 'socket-dc'
                  : null);
    for (final entry in catalogue.values) {
      if (entry.visualType == type && entry.variant == normalized) return entry;
    }
    return null;
  }

  static NativeApplianceGeometry? forSource(SourceInstance c) => forVisual(
    (c.parameters['_visualModelType'] as String?) ?? c.modelType,
    c.parameters['_visualVariant'] as String?,
  );
  static NativeApplianceGeometry? forComponent(ComponentInstance c) {
    final type = (c.parameters['_visualModelType'] as String?) ?? c.modelType;
    var variant = c.parameters['_visualVariant'] as String?;
    if (type == 'catalog_motor_driven_2t' && variant == 'pump') {
      variant = c.modelType == 'motor_dc' ? 'solar-pump' : 'pump-ac1';
    }
    variant ??= type == 'impedance'
        ? 'impedance'
        : type == 'load_wye_3p'
        ? 'load-wye'
        : type == 'load_delta_3p'
        ? 'load-delta'
        : null;
    return forVisual(type, variant);
  }

  static const catalogue = <String, NativeApplianceGeometry>{
"""
if set(DATA) != set(NATIVE_CATALOGUE_ORDER):
    missing = set(NATIVE_CATALOGUE_ORDER) - set(DATA)
    unexpected = set(DATA) - set(NATIVE_CATALOGUE_ORDER)
    raise ValueError(f'Native catalogue key mismatch: missing={missing}, unexpected={unexpected}')

def dart_number(value):
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return repr(value)


lines = [HEADER]
for key in NATIVE_CATALOGUE_ORDER:
    spec = DATA[key]
    width, height = spec['size']
    board_width, board_height = spec['board_size']
    x, y, service_width, service_height = spec['service_box']
    lines.append(
        f"    '{key}': NativeApplianceGeometry(\n"
        f"      key: '{key}',\n"
        f"      visualType: '{spec['type']}',\n"
        f"      variant: '{spec['variant']}',\n"
        f"      designSize: Size({dart_number(width)}, {dart_number(height)}),\n"
        f"      boardSize: Size({dart_number(board_width)}, {dart_number(board_height)}),\n"
        "      ports: [\n"
    )
    for port_x, port_y in spec['ports']:
        lines.append(
            f"        Offset({dart_number(port_x)}, {dart_number(port_y)}),\n"
        )
    lines.append(
        "      ],\n"
        f"      serviceBox: Rect.fromLTWH({dart_number(x)}, {dart_number(y)}, "
        f"{dart_number(service_width)}, {dart_number(service_height)}),\n"
        f"      threePhase: {str(spec['three_phase']).lower()},\n"
        "    ),\n"
    )
lines.append('  };\n}\n')
text = ''.join(lines)
f=ROOT/'packages/electrosim_canvas/lib/src/native_appliance_geometry.dart'
a = argparse.ArgumentParser()
a.add_argument('--check', action='store_true')
opts = a.parse_args()
if opts.check:
    if f.read_text() != text:
        raise SystemExit('Native geometry does not match the unified geometry manifest')
else:
    f.write_text(text)
