import 'dart:convert';
import 'dart:io';

import 'package:electrosim/f18_industrial_physical_plate.dart';
import 'package:flutter_test/flutter_test.dart';

Map<String, dynamic> _json(String path) =>
    jsonDecode(File(path).readAsStringSync()) as Map<String, dynamic>;

void main() {
  final legacyGeometry = _json('assets/g5_industrial/geometry.json');
  final legacyControls = _json('assets/g5_industrial/controls.json');
  final unified = _json('assets/g5_industrial/geometry.unified.json');
  final (geometry, controls) = F18PhysicalPlateAssets.unifiedToLegacy(unified);

  test('unified manifest reproduces every legacy geometry entry', () {
    for (final entry in legacyGeometry.entries) {
      expect(geometry[entry.key], entry.value, reason: entry.key);
    }
  });

  test('unified manifest reproduces every legacy control rectangle', () {
    for (final entry in legacyControls.entries) {
      expect(controls[entry.key], entry.value, reason: entry.key);
    }
  });

  test('every model the plate loader needs is complete in the manifest', () {
    for (final model in F18PhysicalPlateAssets.assetModels) {
      expect(geometry.containsKey(model), isTrue, reason: model);
    }
  });

  test('complete components are well-formed and reference real files', () {
    final components = unified['components'] as Map<String, dynamic>;
    for (final entry in components.entries) {
      final c = entry.value as Map<String, dynamic>;
      for (final path in (c['assets'] as Map<String, dynamic>).values) {
        final file = File('assets/$path');
        if (file.existsSync()) continue;

        // Blender-generated control views are added by the Mac qualification
        // job. Fast Linux test jobs do not render Blender assets themselves.
        if (path is String && path.startsWith('g5_control/')) {
          expect(
            File('../../tools/render_control_components.py').existsSync(),
            isTrue,
            reason: '$path is generated by the Blender qualification job',
          );
          continue;
        }
        fail('Missing manifest asset: $path');
      }
      if (c['status'] != 'complete') continue;
      final size = (c['size'] as List).cast<num>();
      expect(size.every((n) => n > 0), isTrue, reason: entry.key);
      for (final p in (c['ports'] as List).cast<List>()) {
        expect(p[0] as num, inInclusiveRange(0, size[0]), reason: entry.key);
        expect(p[1] as num, inInclusiveRange(0, size[1]), reason: entry.key);
      }
    }
  });

  test('unsupported schema versions are rejected', () {
    expect(
      () => F18PhysicalPlateAssets.unifiedToLegacy({
        'schema_version': 2,
        'components': <String, dynamic>{},
      }),
      throwsFormatException,
    );
  });
}
